#!/usr/bin/env python3
"""out/tokens.json -> out/tokens.css. Never edited by hand."""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "out" / "tokens.json").read_text(encoding="utf-8"))
C, R, D, M = T["color"], T["ramp"], T["density"], T["motion"]
S, A = T["shape"], T["a11y"]


def core():
    out = []
    for k, v in C.items():
        if isinstance(v, dict) and "hex" in v:
            out.append(f"  --{k.replace('_','-')}:{v['hex']};")
    for k, v in C.get("accents", {}).items():
        if isinstance(v, dict):
            out.append(f"  --accent-{k}:{v['hex']};")
    for k, v in C.get("semantic", {}).items():
        if isinstance(v, dict):
            out.append(f"  --{k}:{v['hex']};")
    for k, v in R.items():
        out.append(f"  --{k}:{v};")
    for name, d in D.items():
        n = name[:6]
        out.append(f"  --{n}-row:{d['row']}px; --{n}-pad-y:{d['pad_y']}px; "
                   f"--{n}-pad-x:{d['pad_x']}px; --{n}-text:{d['text']}px;")
    for k, v in M["durations_ms"].items():
        out.append(f"  --dur-{k}:{v}ms;")
    for k, v in M["easing"].items():
        out.append(f"  --ease-{k}:{v};")
    out.append(f"  --radius:{S['surface']}px; --radius-control:{S['control']}px; "
               f"--radius-float:{S['floating']}px;")
    out.append(f"  --target-min:{A['target_min_px']}px;")
    out.append(f"  --row-lh:{list(D.values())[0]['line_height']};")
    ty = T["type"]
    out.append(f"  --display:'{ty['display']['family']}',system-ui,sans-serif;")
    out.append(f"  --text-face:'{ty['text']['family']}',system-ui,sans-serif;")
    out.append(f"  --mono:'{ty['mono']['family']}',ui-monospace,monospace;")
    for k, v in ty["tracking"].items():
        if not k.startswith("$"):
            out.append(f"  --track-{k}:{v};")
    return "\n".join(out)


RETIRED = "\n".join(
    f"   {v}  was {k}" for k, v in C.get("retired", {}).items()
    if not k.startswith("$"))

CSS = f"""/* {T['brand']} — design tokens {T['version']}.
   Generated by build/css.py from out/tokens.json. Do not edit by hand.
   Every contrast ratio in tokens.json was measured, not estimated. */

@import url('fonts-embedded.css');

:root{{
{core()}
}}

/* Images are flex children on most surfaces, and align-items:stretch
   overrides width:auto. Without this a logo becomes an oval and nobody
   can say why. */
img{{width:auto;max-width:100%;align-self:flex-start;flex:0 0 auto}}

body{{font-family:var(--text-face);color:var(--ink);background:var(--ground);
  line-height:1.55;font-synthesis-weight:none;font-synthesis-style:none}}
h1,h2,.display{{font-family:var(--display);
  font-weight:{T['type']['display']['base_weight']};
  letter-spacing:var(--track-lg);line-height:1.02}}
h3,h4,h5{{font-family:var(--display);font-weight:600;
  letter-spacing:var(--track-sm)}}
.accent{{font-family:var(--display);
  font-weight:{T['type']['display']['accent_weight']};color:var(--brand)}}
.on-ink .accent{{color:var(--brand-on-dark)}}

/* Elevation without shadow: surface, border weight, scrim. */
.e1{{background:var(--ground);border:1px solid var(--line)}}
.e2{{background:var(--ground);border:1px solid var(--ink);
  border-radius:var(--radius-float)}}
.e3{{background:var(--ground);border:1.6px solid var(--ink);
  border-radius:var(--radius-float)}}
.scrim{{position:fixed;inset:0;background:color-mix(in srgb,var(--ink) 55%,transparent)}}

:where(a,button,input,select,textarea,[tabindex]):focus-visible{{
  outline:2px solid var(--brand);outline-offset:2px}}
.on-ink :focus-visible{{outline-color:var(--brand-on-dark)}}

.d-comfortable{{--row:var(--comfor-row);--pad-y:var(--comfor-pad-y);
  --pad-x:var(--comfor-pad-x);--text:var(--comfor-text)}}
.d-compact{{--row:var(--compac-row);--pad-y:var(--compac-pad-y);
  --pad-x:var(--compac-pad-x);--text:var(--compac-text)}}
.d-dense{{--row:var(--dense-row);--pad-y:var(--dense-pad-y);
  --pad-x:var(--dense-pad-x);--text:var(--dense-text)}}
:root{{--row:var(--compac-row);--pad-y:var(--compac-pad-y);
  --pad-x:var(--compac-pad-x);--text:var(--compac-text)}}

.btn,.field,.row{{box-sizing:border-box}}
.btn{{border-radius:var(--radius-control);font-weight:600;
  transition:background-color var(--dur-fast) var(--ease-standard)}}
.btn--primary{{background:var(--brand);color:var(--ground);border:none}}
.btn--primary:hover{{background:var(--brand-hover)}}
.btn--primary:active{{background:var(--brand-press);transform:none}}
.btn[disabled]{{background:var(--surface);color:var(--disabled-fg);
  cursor:not-allowed}}
.field{{background:var(--ground);border:1px solid var(--muted);
  border-radius:var(--radius-control);padding:var(--pad-y) var(--pad-x);
  font-size:var(--text);min-height:var(--target-min)}}
.field:hover{{border-color:var(--ink)}}
.field[aria-invalid=true]{{border-color:var(--blocking)}}
.row{{background:var(--ground);border-bottom:1px solid var(--line);
  min-height:var(--row);padding:var(--pad-y) var(--pad-x);
  font-size:var(--text);line-height:var(--row-lh)}}
.row:hover{{background:var(--surface)}}
.row[aria-selected=true]{{background:var(--brand-tint);
  border-left:2px solid var(--brand)}}

@media (prefers-reduced-motion:reduce){{
  *,*::before,*::after{{animation-duration:.001ms !important;
    transition-duration:.001ms !important}}
}}

/* Every responsive breakpoint must be `@media screen and (...)`.
   Chromium uses the CSS page width as the print viewport, so a bare
   query fires during PDF export and collapses every column. */
@media print{{:root{{print-color-adjust:exact;-webkit-print-color-adjust:exact}}}}

/* ── RETIRED. The checker fails on these. ────────────────────────
{RETIRED}
   ─────────────────────────────────────────────────────────────── */
"""

(ROOT / "out" / "tokens.css").write_text(CSS, encoding="utf-8")
print(f"out/tokens.css written · {len(CSS)} bytes")
