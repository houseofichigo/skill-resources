#!/usr/bin/env python3
"""Download the faces named in brand.config.json and emit two stylesheets.

    fonts-embedded.css   base64 — PDF, artifacts, anything offline
    fonts-linked.css     by path — web builds

Fonts come from npm (@fontsource). Never link a font service: a page that
does renders in a fallback face without failing loudly.
"""
import base64, json, pathlib, shutil, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CFG = json.loads((ROOT / "brand.config.json").read_text(encoding="utf-8"))
OUT = ROOT / "out"
VEND = ROOT / ".fonts"
TY = CFG["type"]

LATIN = ("U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,"
         "U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,"
         "U+2212,U+2215,U+FEFF,U+FFFD")
ARABIC = ("U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,"
          "U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,"
          "U+FE70-FE74,U+FE76-FEFC")


def npm_install():
    pkgs = [TY[k]["npm"] for k in ("display", "text", "mono")]
    if "ar" in CFG["locales"]:
        pkgs.append(TY["arabic"]["npm"])
    VEND.mkdir(exist_ok=True)
    # `npm init -y` derives the package name from the folder, and npm
    # rejects a name starting with a dot. Write the manifest directly.
    if not (VEND / "package.json").exists():
        (VEND / "package.json").write_text(
            '{"name":"brand-fonts","private":true,"version":"0.0.0"}\n',
            encoding="utf-8")
    r = subprocess.run(["npm", "i", "--silent"] + pkgs, cwd=VEND,
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"npm install failed:\n{r.stderr[-800:]}")
    return VEND / "node_modules"


def find(nm, pkg, stem):
    p = nm / pkg / "files" / f"{stem}.woff2"
    if not p.exists():
        sys.exit(f"missing {p}\nCheck the 'file' name in brand.config.json "
                 f"against `ls {nm / pkg / 'files'}`")
    return p


def rule(fam, style, weight, src, urange):
    return (f"@font-face{{font-family:'{fam}';font-style:{style};"
            f"font-weight:{weight};font-display:swap;"
            f"src:url({src}) format('woff2');unicode-range:{urange}}}")


def main():
    nm = npm_install()
    faces = []
    for key in ("display", "text", "mono"):
        t = TY[key]
        pkg = t["npm"].split("/")[-1]
        scope = t["npm"].split("/")[0]
        base = nm / scope
        faces.append((t["family"], find(base, pkg, t["file"]),
                      "normal", t["weights"], LATIN))
        if t.get("italic_file"):
            faces.append((t["family"], find(base, pkg, t["italic_file"]),
                          "italic", t["weights"], LATIN))
    if "ar" in CFG["locales"]:
        a = TY["arabic"]
        scope, pkg = a["npm"].split("/")
        for w in a["weights"]:
            faces.append((a["family"],
                          find(nm / scope, pkg,
                               a["file_pattern"].format(w=w)),
                          "normal", str(w), ARABIC))

    OUT.mkdir(exist_ok=True)
    fdir = OUT / "fonts"
    fdir.mkdir(exist_ok=True)
    emb, lnk, total = [], [], 0
    head = (f"/* {CFG['brand']} — type. Generated by build/fonts.py.\n"
            f"   Do not edit by hand. Never link a font service. */\n")
    emb.append(head)
    lnk.append(head)
    for fam, p, style, weight, urange in faces:
        raw = p.read_bytes()
        total += len(raw)
        emb.append(rule(fam, style, weight,
                        f"data:font/woff2;base64,"
                        f"{base64.b64encode(raw).decode()}", urange))
        shutil.copy(p, fdir / p.name)
        lnk.append(rule(fam, style, weight, f"fonts/{p.name}", urange))

    (OUT / "fonts-embedded.css").write_text("\n".join(emb), encoding="utf-8")
    (OUT / "fonts-linked.css").write_text("\n".join(lnk), encoding="utf-8")
    print(f"{len(faces)} faces · {total/1024:.0f} KB raw "
          f"· embedded {len(chr(10).join(emb))/1024:.0f} KB")


if __name__ == "__main__":
    main()
