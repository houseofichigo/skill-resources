def _hero(h):
    return h.replace('class="c-hero"', 'class="c-hero" data-section="hero" data-surface="white"', 1)


def idt(ctx, path, value):
    """Identity text as (raw text, attrs): copy.<lang>.identity.<path> when
    the config has it, else the identity value marked lang="en"."""
    if ctx.lang != "en":
        v = ctx._lookup(ctx.lang, "identity." + path)
        if isinstance(v, str):
            return v, ""
        if value:
            ctx.fallbacks.add("identity." + path)
            return value, ' lang="en"'
    return value or "", ""


