def file_of(ptype, pillar=None):
    if ptype == "not_found":
        return "not-found.html"
    if ptype == "pillar" and pillar:
        return f"pillar-{pillar['key']}.html"
    return f"{ptype}.html"


def set_links(ctx, pages, lang, en_lang, fname):
    """Hrefs from the page being rendered: same-language siblings, and the
    language switch to this page in the other language."""
    L = {}
    for ptype, pl in pages:
        f = file_of(ptype, pl)
        key = f"pillar-{pl['key']}" if pl else ("not_found" if ptype == "not_found" else ptype)
        L[key] = f
    L["home"] = L.get("home", "#")
    for l in ctx.locs:
        if l == lang:
            L["lang-" + l] = fname
        elif l == en_lang:
            L["lang-" + l] = "../" + fname
        elif lang == en_lang:
            L["lang-" + l] = f"{l}/{fname}"
        else:
            L["lang-" + l] = f"../{l}/{fname}"
    ctx.links = L


