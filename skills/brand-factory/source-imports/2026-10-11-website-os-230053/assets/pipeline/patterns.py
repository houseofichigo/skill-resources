# ── cadence: read back from the page ─────────────────────────────────────
def cadence(html_):
    """Read the sections back out of the generated HTML. A warning is a
    failure: p45's 'two or three white per Ink' is a rule, not advice."""
    seq = []
    for tag in re.findall(r"<(?:section|div)\b[^>]*\bdata-section=[^>]*>", html_):
        n = re.search(r'data-section="([^"]+)"', tag).group(1)
        s = re.search(r'data-surface="(white|ink)"', tag)
        seq.append((n, s.group(1) if s else "white"))
    names = [s for s, _ in seq]
    surf = [x for _, x in seq]
    errs, warns = cadence_check(surf, names)
    return names, [n for n, x in seq if x == "ink"], {"pass": not errs and not warns, "errors": errs + warns, "warnings": []}


# ── gates the page set adds ──────────────────────────────────────────────
def page_text(doc):
    """The visible text of a page: no script, style, tags or attributes."""
    t = re.sub(r"<(script|style)\b.*?</\1>", " ", doc, flags=re.S | re.I)
    t = re.sub(r"<[^>]+>", " ", t)
    return re.sub(r"\s+", " ", html.unescape(t)).strip()


def config_notes(cfg):
    """Every $note / $note_* / $comment string in the config (factory and
    provenance text that must never be page copy)."""
    out = []

    def walk(n):
        if isinstance(n, dict):
            for k, v in n.items():
                if isinstance(v, str) and (k == "$comment" or k.startswith("$note")):
                    out.append(v)
                else:
                    walk(v)
        elif isinstance(n, list):
            for x in n:
                walk(x)
    walk(cfg)
    return [x for x in dict.fromkeys(out) if len(x.strip()) >= 16]


