# ── cadence: plan, then read back from the page ──────────────────────────
def cadence_check(surf, names):
    errs, warns = [], []
    for k in range(1, len(surf)):
        if surf[k] == surf[k - 1] == "ink":
            errs.append(f"two Ink sections adjacent: {names[k - 1]} · {names[k]}")
    if "cta_band" in names and names[-1] != "cta_band":
        errs.append("the CTA band is not the last section")
    inks = [k for k, x in enumerate(surf) if x == "ink"]
    for a, b in zip(inks, inks[1:]):
        if b - a - 1 < 2:
            warns.append(f"only {b - a - 1} white section(s) between Ink {names[a]} and {names[b]} (cadence asks two or three)")
    if inks and surf.count("white") < 2 * len(inks):
        warns.append(f"{len(inks)} Ink to {surf.count('white')} white — more than one per two")
    return errs, warns


def plan_cadence(items):
    """A planned sequence that breaks p45 (an Ink between fewer than two
    whites) is repaired: a mid-page Ink section moves to the nearest place
    that satisfies the cadence (never before the hero, never after the CTA
    band); if none does, it is dropped. → (items, note or None)."""
    def ok(seq):
        e, w = cadence_check([s for _, s in seq], [l.split(" ")[0].lower() for l, _ in seq])
        return not e and not w
    if ok(items):
        return items, None
    mids = [k for k, (l, s) in enumerate(items) if s == "ink" and not l.lower().startswith("cta_band")]
    for k in mids:
        rest = items[:k] + items[k + 1:]
        for d in sorted(range(1, len(rest)), key=lambda j: abs(j - k)):
            cand = rest[:d] + [items[k]] + rest[d:]
            if cand[-1][0].lower().startswith("cta_band") or not any(l.lower().startswith("cta_band") for l, _ in items):
                if ok(cand):
                    return cand, (f"cadence (p45): '{items[k][0]}' moved from position {k + 1} to {d + 1} — "
                                  f"the planned order put fewer than two white sections between Ink sections; "
                                  f"fix patterns.web.pages in the config")
    for k in mids:
        cand = items[:k] + items[k + 1:]
        if ok(cand):
            return cand, f"cadence (p45): '{items[k][0]}' dropped — no position satisfies the cadence"
    return items, None


