def authored_css(ctx):
    am = ((ctx.cfg.get("motion") or {}).get("authored_moment")) or {}
    tl = am.get("timeline") or []
    S = Sheet()
    if not tl or not ctx.comp("quadrant"):
        return S
    stag = ((ctx.cfg.get("motion") or {}).get("stagger_ms") or {})
    stag = stag.get("value", 40) if isinstance(stag, dict) else (stag or 40)
    S.raw("/* the authored moment (motion.authored_moment): the quadrant drawing in, once */")
    S.raw("@keyframes am-draw { to { stroke-dashoffset: 0; } }")
    S.raw("@keyframes am-fade { to { opacity: 1; } }")
    S.raw("@keyframes am-dot { to { opacity: 1; transform: scale(1); } }")
    A = ".is-armed"
    S.rule(f"{A} .c-quad__axis-title, {A} .c-quad__zone, {A} .c-quad__label", [("opacity", "0")])
    S.rule(f"{A} .c-quad__dot::before", [("opacity", "0"), ("transform", "scale(0.9)")])
    S.rule(".is-armed-rm .c-quad__plot, .is-armed-rm .c-quad__axis-title", [("opacity", "0")])
    S.rule(".is-armed-rm.is-playing .c-quad__plot, .is-armed-rm.is-playing .c-quad__axis-title",
           [("animation", "am-fade var(--motion-opacity-fast) var(--ease-standard) forwards")])
    data, _ = C.examples(ctx)
    for e in tl:
        el, prop = str(e.get("element", "")), str(e.get("property", ""))
        t0 = int(e.get("t_ms", 0))
        dur = f"var(--motion-{e.get('duration', 'base')})"
        dur_o = f"var(--motion-opacity-{e.get('duration', 'base')})"
        ease = f"var(--ease-{e.get('easing', 'standard')})"
        P = f"{A}.is-playing"
        if el.startswith("x and y axes") or el.startswith("axes"):
            S.rule(f"{P} .c-quad__axis", [("animation", f"am-draw {dur} {ease} {t0}ms forwards")])
        elif "axis titles" in el:
            S.rule(f"{P} .c-quad__axis-title", [("animation", f"am-fade {dur_o} {ease} {t0}ms forwards")])
        elif "segment" in el:
            m = re.search(r"segment (\d+)", el)
            S.rule(f'{P} .c-quad__cut[data-seg="{m.group(1)}"]', [("animation", f"am-draw {dur} {ease} {t0}ms forwards")])
        elif "zone labels" in el:
            for k in range(4):
                S.rule(f'{P} .c-quad__zone[data-z="{k}"]', [("animation", f"am-fade {dur_o} {ease} {t0 + k * stag}ms forwards")])
        elif el.startswith("dots"):
            for k in range(len(data)):
                S.rule(f'{P} .c-quad__dot[data-d="{k}"]::before', [("animation", f"am-dot {dur} {ease} {t0 + k * stag}ms forwards")])
        elif "dot labels" in el:
            for k in range(len(data)):
                S.rule(f'{P} .c-quad__dot[data-d="{k}"] > span', [("animation", f"am-fade {dur_o} {ease} {t0 + k * stag}ms forwards")])
    return S


def authored_js(ctx):
    am = ((ctx.cfg.get("motion") or {}).get("authored_moment")) or {}
    m = re.search(r"threshold\s*([\d.]+)", str(am.get("trigger", "")))
    th = float(m.group(1)) if m else 0.5
    total = int(am.get("total_ms") or 1100)
    return f"""(function () {{
  // motion.authored_moment: armed before first paint, played once at threshold {th:g},
  // then handed back to its resting state (no class, no inline style) at {total}ms.
  var el = document.querySelector('[data-authored="quadrant"]');
  if (!el || !('IntersectionObserver' in window)) return;
  var rm = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var lines = el.querySelectorAll('.c-quad__axis, .c-quad__cut');
  if (!rm) {{
    // a line draws from its start: dash = its rendered length (axis-aligned)
    lines.forEach(function (l) {{
      var r = l.getBoundingClientRect(), n = Math.ceil(Math.max(r.width, r.height)) + 2;
      l.style.strokeDasharray = n + 'px';
      l.style.strokeDashoffset = n + 'px';
    }});
  }}
  el.classList.add(rm ? 'is-armed-rm' : 'is-armed');
  var io = new IntersectionObserver(function (entries) {{
    entries.forEach(function (e) {{
      if (!e.isIntersecting) return;
      io.disconnect();
      document.fonts.ready.then(function () {{
        el.classList.add('is-playing');
        setTimeout(function () {{
          el.classList.remove('is-armed', 'is-armed-rm', 'is-playing');
          lines.forEach(function (l) {{ l.style.strokeDasharray = ''; l.style.strokeDashoffset = ''; }});
        }}, {total} + 60);
      }});
    }});
  }}, {{ threshold: {th:g} }});
  io.observe(el);
}})();"""


