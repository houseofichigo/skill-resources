#!/usr/bin/env python3
"""The token tree → out/tokens/tokens.css: the CSS binding every v2 output
reads (components, patterns, the site's index.css, tailwind-v4.css).

    python3 build/tokens_css.py

The contract — other generators and the site depend on it:

  · One custom property per token: "--" + the token name with "." and "_"
    turned into "-".   color.state.accent_hover → --color-state-accent-hover
                       color.tint.accent.8     → --color-tint-accent-8
                       radius.control          → --radius-control
  · Typography tokens split into parts: --type-<role>-size (fluid clamp from
    phone to desktop), -size-<breakpoint>, -lh, -weight, -family, -tracking.
  · Elevation: --elevation-<level>-surface, -border, -scrim.
  · Motion: --motion-<duration> and --ease-<name>. Under reduced motion every
    --motion-<duration> drops to 0 when the brand says so (motion.reduced_motion);
    --motion-opacity-<duration> survive, and when the rule names the one opacity
    keeps ("… except opacity, which keeps fast") every longer opacity duration
    becomes that one.
  · Type tracking: --type-<role>-tracking follows the role's px band at each
    breakpoint (a @media screen block per breakpoint where the band changes).
  · Layout and density, from the config: --grid-<bp>-columns|gutter|margin,
    --container-max, --section-y-<bp>, --density-<scale>-row|pad-x|pad-y|text|label.
  · The brand's own names (color.roles.*.token, e.g. --cobalt) are emitted
    as aliases, so pages written against the brand's old stylesheet keep
    rendering.
  · [data-surface=ink] remaps the roles for a dark SURFACE (color.dark.surfaces).
    [data-theme=dark] is emitted only when color.dark.theme is a real table.
  · [dir=rtl] / :lang(ar) switches the text face and applies the Arabic
    scale, line-height and row bumps when "ar" is a locale.

No literal value appears twice: everything after :root is var().
Standard library only.
"""
import pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from config import load, ConfigError  # noqa: E402
from tree import build_tree, REF  # noqa: E402

ROOT = HERE.parent
OUT = ROOT / "out" / "tokens"


def css_var(name):
    return "--" + re.sub(r"[._]", "-", name)


def ref_var(v, palette=False):
    """'{color.accent}' → 'var(--color-accent)'; anything else unchanged.
    palette=True points a one-level colour role at its immutable layer."""
    if isinstance(v, str):
        m = REF.match(v)
        if m:
            name = m.group(1)
            if palette and name.startswith("color.") and name.count(".") == 1:
                return f"var({css_var(name).replace('--color-', '--palette-')})"
            return f"var({css_var(name)})"
    return v


def dim(v):
    if isinstance(v, dict) and "value" in v:
        return f"{v['value']:g}{v.get('unit', 'px')}"
    return str(v)


def font_stack(v):
    if isinstance(v, list):
        return ", ".join(f"'{f}'" if " " in f or f[0].isupper() and f not in ("system-ui",) else f
                         for f in v)
    return str(v)


def clamp(px_min, px_max, vw_min, vw_max):
    """A fluid size between two viewports, in rem for zoom."""
    if px_min == px_max:
        return f"{px_max / 16:g}rem"
    slope = (px_max - px_min) / (vw_max - vw_min)
    inter = px_min - slope * vw_min
    return (f"clamp({px_min / 16:g}rem, {inter / 16:.4f}rem + {slope * 100:.4f}vw, "
            f"{px_max / 16:g}rem)")


def build(cfg, t):
    T = t["tokens"]
    L = [f"/* {cfg['brand']} {cfg['version']} — tokens.css. Generated by build/tokens_css.py",
         "   from brand.config.json. Do not edit: change the config and rebuild. */", "",
         ":root {"]

    def put(name, value, note=None):
        L.append(f"  {name}: {value};" + (f" /* {note} */" if note else ""))

    groups = {}
    for name, tok in sorted(T.items()):
        groups.setdefault(name.split(".")[0], []).append((name, tok))

    # colours (retired ones are not emitted: their absence is the point)
    L.append("  /* colour */")
    # Roles sit on an immutable palette layer: a scope that remaps roles
    # (an Ink surface swaps bg and fg) must point at --palette-*, never at
    # another role, or the two definitions become circular and both die.
    for name, tok in groups.get("color", []):
        if name.startswith("color.retired."):
            continue
        v = ref_var(tok["value"])
        if name.count(".") == 1 and not str(v).startswith("var("):
            put(css_var(name).replace("--color-", "--palette-"), v)
            v = f"var({css_var(name).replace('--color-', '--palette-')})"
        put(css_var(name), v)
    L.append("  /* brand names, as aliases */")
    for role, node in sorted((cfg["color"].get("roles") or {}).items()):
        if isinstance(node, dict) and node.get("token") and f"color.{role}" in T:
            put(node["token"], f"var({css_var('color.' + role)})")
    for k, node in sorted((cfg["color"].get("semantic") or {}).items()):
        if isinstance(node, dict) and node.get("token") and f"color.semantic.{k}" in T:
            put(node["token"], f"var({css_var('color.semantic.' + k)})")

    L.append("  /* type */")
    for name, tok in groups.get("font", []):
        put(css_var(name), font_stack(tok["value"]))
    vw = cfg["type"]["scale"].get("fluid", {})
    vw_min, vw_max = vw.get("min_viewport", 375), vw.get("max_viewport", 1280)
    order = (cfg.get("layout") or {}).get("breakpoints", {}).get("order", [])
    mins = (cfg.get("layout") or {}).get("breakpoints", {}).get("min", {})
    track_mq = {}   # breakpoint → [(var, value)]: tracking follows the px band of the size AT that breakpoint
    for name, tok in groups.get("type", []):
        v, ext = tok["value"], tok.get("extensions", {})
        base = css_var(name)
        size = v["fontSize"]["value"]
        bps = ext.get("breakpoints", {})
        phone = bps.get("phone", {}).get("fontSize", {}).get("value", size)
        put(f"{base}-size", clamp(phone, size, vw_min, vw_max))
        for bp, part in sorted(bps.items()):
            if "fontSize" in part:
                put(f"{base}-size-{bp}", dim(part["fontSize"]))
        put(f"{base}-size-desktop", dim(v["fontSize"]))
        put(f"{base}-lh", f"{v['lineHeight']:g}")
        put(f"{base}-weight", v["fontWeight"])
        put(f"{base}-family", ref_var(v["fontFamily"]))
        dflt = ext.get("default_breakpoint")
        per = {b: (bps.get(b) or {}).get("letterSpacing") for b in order}
        if dflt in per:
            per[dflt] = v.get("letterSpacing", "0")
        seq = [(b, per[b]) for b in order if per.get(b) is not None]
        first = seq[0][1] if seq else ext.get("letterSpacing_css", v.get("letterSpacing", "0"))
        put(f"{base}-tracking", first)
        prev = first
        for b, val in seq[1:]:
            if val != prev:
                track_mq.setdefault(b, []).append((f"{base}-tracking", val))
                prev = val

    L.append("  /* shape, space, elevation */")
    for g in ("radius", "space"):
        for name, tok in groups.get(g, []):
            put(css_var(name), dim(tok["value"]))
    for name, tok in groups.get("elevation", []):
        v, base = tok["value"], css_var(name)
        put(f"{base}-surface", ref_var(v.get("surface", "transparent")))
        b = v.get("border")
        if isinstance(b, dict):
            put(f"{base}-border", f"{dim(b['width'])} {b.get('style', 'solid')} {ref_var(b['color'])}")
        else:
            put(f"{base}-border", "none")
        put(f"{base}-scrim", ref_var(v.get("scrim")) if v.get("scrim") not in (None, "none") else "transparent")

    L.append("  /* motion */")
    for name, tok in groups.get("motion", []):
        put(css_var(name), dim(tok["value"]))
        put(css_var(name).replace("--motion-", "--motion-opacity-"), dim(tok["value"]))
    for name, tok in groups.get("ease", []):
        put(css_var(name), "cubic-bezier(" + ", ".join(f"{x:g}" for x in tok["value"]) + ")")

    L.append("  /* layout */")
    lay = cfg["layout"]
    for name, tok in groups.get("breakpoint", []):
        put(css_var(name), dim(tok["value"]), "reference only: media queries cannot read it")
    for bp, g in (lay.get("grid") or {}).items():
        if bp.startswith("$") or not isinstance(g, dict) or "columns" not in g:
            continue
        put(f"--grid-{bp}-columns", g["columns"])
        put(f"--grid-{bp}-gutter", f"{g['gutter']}px")
        put(f"--grid-{bp}-margin", f"{g['margin']}px")
    cm = (lay.get("containers") or {}).get("max")
    if cm:
        put("--container-max", f"{cm}px")
    pc = (lay.get("containers") or {}).get("prose_ch")
    if pc:
        put("--measure", f"{pc}ch")
    for bp, v in (lay.get("section_rhythm") or {}).items():
        if bp.startswith("$"):
            continue
        v = v.get("value") if isinstance(v, dict) else v
        if v is not None:
            put(f"--section-y-{bp}", f"{v}px")

    dens = cfg["density"]
    lh = dens["line_height"]
    for k, d in dens["scales"].items():
        if k.startswith("$"):
            continue
        line = d["text"] * lh
        pad = round((d["row"] - line) / 2)
        put(f"--density-{k}-row", f"{d['row']}px")
        put(f"--density-{k}-pad-x", f"{d['pad_x']}px")
        put(f"--density-{k}-pad-y", f"{pad}px")
        put(f"--density-{k}-text", f"{d['text']}px")
        put(f"--density-{k}-label", f"{d['label']}px")
    put("--target-min", f"{cfg['a11y']['target_min_px']}px")
    L.append("}")

    # tracking by breakpoint: a display size of 36px on a phone takes the
    # 24–42 band, not the desktop size's band (type.tracking.bands)
    for b in order:
        if track_mq.get(b) and mins.get(b):
            L += ["", f"@media screen and (min-width: {mins[b]}px) {{", "  :root {"]
            L += [f"    {n}: {val};" for n, val in track_mq[b]]
            L += ["  }", "}"]

    # reduced motion
    rm = cfg["motion"].get("reduced_motion") or {}
    rule = rm.get("rule", "") if isinstance(rm, dict) else str(rm)
    if re.search(r"0\s*ms", rule):
        L += ["", f"/* reduced motion: {rule.strip()} */",
              "@media (prefers-reduced-motion: reduce) {", "  :root {"]
        # "… except opacity, which keeps <duration>": every opacity duration
        # becomes that one; without such a clause opacity keeps its own values
        keep = re.search(r"opacity[^.]*?keeps?\s+(?:the\s+)?([\w-]+)", rule)
        keep = keep.group(1) if keep and f"motion.{keep.group(1)}" in T else None
        kv = (T.get(f"motion.{keep}") or {}).get("value", {}).get("value", 0) if keep else 0
        for name, tok in groups.get("motion", []):
            L.append(f"    {css_var(name)}: 0ms;")
            # instant stays instant: only longer opacity fades shorten to the kept one
            if keep and name != f"motion.{keep}" and (tok["value"].get("value", 0) if isinstance(tok["value"], dict) else 0) > kv:
                L.append(f"    {css_var(name).replace('--motion-', '--motion-opacity-')}: "
                         f"var({css_var('motion.' + keep).replace('--motion-', '--motion-opacity-')});")
        L += ["  }", "}"]

    # dark surface (not a theme)
    D = (cfg["color"].get("dark") or {})
    S = D.get("surfaces") or {}
    if S.get("bg"):
        def surf(key):
            v = S.get(key)
            return v
        L += ["", "/* a dark SURFACE (color.dark.surfaces) — Ink sections, the sidebar. Not a theme. */",
              "[data-surface=ink] {"]
        L.append(f"  --color-bg: {ref_var(_role_ref(cfg, S['bg']), palette=True)};")
        if S.get("fg"):
            L.append(f"  --color-fg: {ref_var(_role_ref(cfg, S['fg']), palette=True)};")
        if S.get("muted"):
            L.append(f"  --color-muted: {ref_var(_role_ref(cfg, S['muted']), palette=True)};")
        if S.get("accent_text"):
            L.append(f"  --color-accent-text: {ref_var(_role_ref(cfg, S['accent_text']), palette=True)};")
        if S.get("focus"):
            L.append(f"  --color-focus: {ref_var(_role_ref(cfg, S['focus']), palette=True)};")
        L += ["  background-color: var(--color-bg);", "  color: var(--color-fg);", "}"]
    theme = D.get("theme")
    if isinstance(theme, dict) and theme:
        L += ["", "[data-theme=dark] {"]
        for role, v in sorted(theme.items()):
            if not role.startswith("$"):
                L.append(f"  {css_var('color.' + role)}: {ref_var(v)};")
        L.append("}")

    # RTL / Arabic
    if "ar" in cfg["locales"]["list"] and "font.arabic" in T:
        ar = cfg["type"]["families"].get("arabic", {})
        L += ["", "/* Arabic and RTL (type.families.arabic, density.rtl_row_bump) */",
              ":lang(ar), [dir=rtl] {",
              "  --font-text: var(--font-arabic);",
              "  --font-display: var(--font-arabic);",
              f"  --type-scale: {ar.get('scale', 1)};",
              f"  --type-lh-bump: {ar.get('line_height_bump', 0)};"]
        bump = (dens.get("rtl_row_bump") or {})
        bump = bump.get("value", 0) if isinstance(bump, dict) else bump
        for k, d in dens["scales"].items():
            if not k.startswith("$") and bump:
                L.append(f"  --density-{k}-row: {round(d['row'] * (1 + bump))}px;")
        L += ["}"]

    # the colour accent text default on light surfaces
    L += ["", ":root { --color-accent-text: var(--color-accent); --color-focus: var(--color-accent); }", ""]
    return "\n".join(L)


def _role_ref(cfg, v):
    """A dark-surface value: a hex or rgba literal that equals a role becomes
    that role's reference, so the surface stays bound to the palette."""
    if isinstance(v, str) and not REF.match(v):
        for role, node in (cfg["color"].get("roles") or {}).items():
            if isinstance(node, dict) and (node.get("hex") or "").upper() == v.upper():
                return "{color.%s}" % role
            if isinstance(node, dict) and str(node.get("value", "")).replace(" ", "") == v.replace(" ", ""):
                return "{color.%s}" % role
    return v


def main():
    try:
        cfg, _, a = load()
    except ConfigError as e:
        sys.exit(f"config gate failed:\n  {e}")
    t = build_tree(cfg, a)
    css = build(cfg, t)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tokens.css").write_text(css, encoding="utf-8")
    n = css.count(";\n")
    # gate: every var() used is defined
    defined = set(re.findall(r"(--[\w-]+)\s*:", css))
    used = set(re.findall(r"var\((--[\w-]+)\)", css))
    missing = sorted(used - defined)
    if missing:
        print("FAILED · var() with no definition: " + ", ".join(missing))
        sys.exit(1)
    print(f"out/tokens/tokens.css written · {len(defined)} custom properties, every var() defined")


if __name__ == "__main__":
    main()
